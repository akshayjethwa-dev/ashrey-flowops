// src/types/mrp.ts

import { StockCategory } from '../types';

export type MrpHorizon = 7 | 14 | 30 | 60 | 90;

export type MrpRunMode = 'manual' | 'scheduled';

export type MrpRecommendationUrgency = 'critical' | 'high' | 'medium' | 'planned';

export type MrpRecommendationStatus = 'pending' | 'approved' | 'po_created' | 'dismissed';

export type SafetyStockRuleType = 'fixed_units' | 'days_of_supply' | 'reorder_point';

/**
 * Safety stock calculation rules per material or category
 */
export interface SafetyStockRule {
  id: string;
  stockItemId?: string;
  category?: StockCategory | 'all';
  ruleType: SafetyStockRuleType;
  fixedBufferQty: number;          // e.g. 5.0 tonnes
  bufferDays: number;              // e.g. 7 days of average production consumption
  minOrderQty: number;             // MOQ e.g. 2.0 tonnes
  orderMultiple: number;           // Must order in multiples of e.g. 0.5 tonnes
  shrinkageAllowancePct: number;   // Scrap / cut-off allowance e.g. 2%
  inspectionBufferDays: number;    // Receiving dock inspection time e.g. 1 day
}

/**
 * Gross material demand item exploded from active Work Orders
 */
export interface MrpGrossDemandItem {
  id: string;
  stockItemId: string;
  stockItemCode: string;
  stockItemName: string;
  workOrderId: string;
  workOrderNumber: string;
  salesOrderNumber?: string;
  productPartName: string;
  requiredDate: string;            // Need-by date on factory floor
  quantity: number;
  unit: string;
  plantId: string;
  plantName: string;
}

/**
 * Single actionable purchase recommendation generated by MRP Engine
 */
export interface MrpPurchaseRecommendation {
  id: string;
  runId: string;
  tenantId: string;
  plantId: string;
  plantName: string;

  // Material Details
  stockItemId: string;
  stockItemCode: string;
  stockItemName: string;
  category: StockCategory;
  unit: string;
  unitCost: number;

  // Inventory Position at time of calculation
  currentOnHand: number;
  reservedQty: number;
  availableStock: number;          // Math.max(0, currentOnHand - reservedQty)
  scheduledInbound: number;        // Pending POs already in pipeline

  // Planning Calculations
  safetyStockRequired: number;     // Configured safety stock buffer
  grossRequirement: number;        // Sum of all WO demands in horizon
  netRequirement: number;          // Gross + Safety - (Available + Inbound)
  recommendedOrderQty: number;     // Adjusted for MOQ & order multiples
  totalEstimatedCost: number;      // recommendedOrderQty * unitCost (in INR)

  // Lead Time & Date Scheduling (Core Acceptance Criteria)
  leadTimeDays: number;            // Vendor manufacturing & transit time
  inspectionBufferDays: number;    // Receiving dock inspection lag
  needByDate: string;              // Date material is consumed in production
  orderByDate: string;             // Date PO must be released to vendor
  expectedDeliveryDate: string;    // orderByDate + leadTimeDays
  slackDays: number;               // Days until orderByDate (negative = overdue/critical)

  // Vendor & Procurement
  preferredSupplierId?: string;
  preferredSupplierName: string;
  vendorPaymentTerms?: string;
  moq: number;
  orderMultiple: number;

  // Status & Urgency
  urgency: MrpRecommendationUrgency;
  status: MrpRecommendationStatus;
  poNumber?: string;               // Assigned once converted to PO
  convertedAt?: string;
  convertedByName?: string;
  notes: string;

  // Demand traceability
  demandsBreakdown: Array<{
    workOrderNumber: string;
    productPartName: string;
    qty: number;
    requiredDate: string;
  }>;
}

/**
 * Historical record of an MRP run
 */
export interface MrpRunRecord {
  id: string;
  runNumber: string;               // e.g. "MRP-2026-0042"
  tenantId: string;
  plantId: string;                 // 'all' or specific plantId
  plantName: string;
  triggeredAt: string;
  triggeredByUserId: string;
  triggeredByName: string;
  runMode: MrpRunMode;
  horizonDays: MrpHorizon;
  totalMaterialsAnalyzed: number;
  totalDemandQty: number;
  recommendationsCount: number;
  criticalRecommendationsCount: number;
  totalRecommendedSpend: number;   // Sum of recommended PO costs in INR
  runtimeMs: number;
  status: 'completed' | 'failed';
  summaryMessage: string;
}

/**
 * Automation & Schedule Configuration
 */
export interface MrpScheduleConfig {
  enabled: boolean;
  frequency: 'daily' | 'shift' | 'weekly';
  timeOfDay: string;               // e.g. "06:00"
  horizonDays: MrpHorizon;
  plantId: string;                 // 'all' or specific
  autoNotifyProcurement: boolean;
  notifyEmail?: string;
  lastRunAt?: string;
  nextRunAt: string;
  safetyStockMultiplier: number;   // e.g. 1.0 (normal) or 1.2 (+20% safety during peak season)
}
