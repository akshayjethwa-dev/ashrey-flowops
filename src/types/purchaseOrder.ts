// src/types/purchaseOrder.ts

import { StockCategory } from '../types';

export type PurchaseOrderStatus =
  | 'draft'               // Auto-generated by reorder trigger or created by buyer
  | 'pending_approval'   // Routed to procurement manager / finance for approval
  | 'approved'           // Approved and ready for supplier dispatch
  | 'rejected'           // Rejected by approver
  | 'issued'             // Dispatched to supplier (awaiting acknowledgment)
  | 'acknowledged'       // Supplier confirmed delivery date & agreed terms
  | 'in_transit'         // Supplier dispatched lorry / shipment
  | 'partially_received' // Partial dock arrival
  | 'received'           // Fully received & inwarded into storage bins
  | 'cancelled';

export type PoApprovalStatus = 'not_required' | 'pending' | 'approved' | 'rejected';

export type SupplierAckStatus =
  | 'pending'
  | 'acknowledged_on_time'
  | 'counter_proposed_date'
  | 'rejected_by_supplier';

export type PoSourceTrigger =
  | 'reorder_level_breach' // Auto-generated when bin/plant stock fell below minimum threshold
  | 'mrp_engine'           // Auto-generated from MRP explosion netting
  | 'manual_buyer';        // Created manually by procurement officer

export interface PurchaseOrderItem {
  id: string;
  stockItemId: string;
  stockItemCode: string;
  stockItemName: string;
  category: StockCategory;
  orderedQty: number;
  receivedQty: number;
  unit: string;
  unitPrice: number;            // in INR
  taxRatePct: number;           // e.g. 18% GST
  taxAmount: number;            // (orderedQty * unitPrice) * taxRatePct / 100
  totalAmount: number;          // (orderedQty * unitPrice) + taxAmount
  hsnCode?: string;             // Indian GST HSN/SAC code
  targetBinId?: string;
  targetBinCode?: string;
  targetStoreId?: string;
  targetStoreName?: string;
  needByDate?: string;          // Shopfloor consumption date
}

export interface PoApprovalAuditEntry {
  id: string;
  stepName: string;             // e.g. "Procurement Manager Review" or "Finance Sign-off"
  approverId: string;
  approverName: string;
  approverRole: string;
  action: 'approved' | 'rejected' | 'requested_revision';
  timestamp: string;
  comments?: string;
}

export interface SupplierAcknowledgment {
  status: SupplierAckStatus;
  acknowledgedAt?: string;
  acknowledgedByName?: string;
  vendorConfirmationRef?: string;  // e.g. Vendor Sales Order / Ack #
  originalExpectedDate: string;
  confirmedExpectedDate: string;   // Confirmed delivery date by supplier
  counterProposalReason?: string;
  trackingCarrier?: string;        // e.g. "VRL Logistics", "TCI Freight"
  lorryReceiptNumber?: string;     // Lorry Receipt (LR) # or Tracking AWB
  dispatchDate?: string;
  notes?: string;
}

export interface PurchaseOrder {
  id: string;
  tenantId: string;
  poNumber: string;                // e.g. "PO-2026-1048"
  sourceTrigger: PoSourceTrigger;
  triggerReference?: string;       // e.g. "Stock fell to 3.2T (Min: 6.0T)" or "MRP-2026-0038"

  // Facility Scope
  plantId: string;
  plantName: string;
  shipToAddress?: string;
  billingAddress?: string;

  // Supplier Details
  supplierId: string;
  supplierName: string;
  supplierEmail?: string;
  supplierPhone?: string;
  supplierGstin?: string;
  supplierContactPerson?: string;
  paymentTerms: string;            // e.g. "Net 30 Days", "Advance 20% / Balance on Delivery"
  deliveryTerms: string;           // e.g. "FOR Destination (Plant Gate)", "Ex-Works"

  // Dates & Timeline
  orderDate: string;
  expectedDeliveryDate: string;    // Core Acceptance Criteria
  needByDate: string;              // When factory floor needs the stock
  actualDeliveryDate?: string;

  // Line items
  items: PurchaseOrderItem[];
  subtotal: number;
  totalTax: number;
  totalAmount: number;             // Total PO value in INR

  // Approval Workflow (Core Acceptance Criteria)
  approvalStatus: PoApprovalStatus;
  approvalRequired: boolean;
  approvalLimitTier: 'auto_approved' | 'manager_level' | 'executive_level';
  approvalsHistory: PoApprovalAuditEntry[];
  currentPendingApproverRole?: string;

  // Supplier Acknowledgment Tracking (Core Acceptance Criteria)
  supplierAck: SupplierAcknowledgment;

  // Lifecycle Status
  status: PurchaseOrderStatus;

  // Audit
  createdById: string;
  createdByName: string;
  createdAt: string;
  updatedAt: string;
  notes?: string;
}

export interface PoAutomationRule {
  id: string;
  tenantId: string;
  enabled: boolean;
  autoApproveUnderAmount: number;  // e.g. ₹50,000 auto-approved
  managerApprovalLimit: number;    // up to ₹5,00,000
  autoNotifyVendorOnApproval: boolean;
  notifyChannel: 'whatsapp' | 'email' | 'both';
  safetyStockBufferMultiplier: number;
}
